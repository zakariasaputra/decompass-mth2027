def _find_idsse_files(idsse_dir, match_id):
    meta = glob.glob(os.path.join(idsse_dir, f"*matchinformation*{match_id}*.xml"))
    trk = glob.glob(os.path.join(idsse_dir, f"*positions_raw*{match_id}*.xml"))
    if not meta or not trk:
        raise FileNotFoundError(
            f"Missing IDSSE XML files for {match_id} in {idsse_dir}. "
            "Run `python tools/fetch_external.py --only idsse` first."
        )
    return meta[0], trk[0]


def load_idsse_centered(match_id, idsse_dir):
    """Load an IDSSE Bundesliga match in centered meters with raw BallStatus/BallPossession labels."""
    meta_path, trk_path = _find_idsse_files(idsse_dir, match_id)
    mroot = ET.parse(meta_path).getroot()
    home_team = away_team = None
    for team in mroot.iter("Team"):
        role = team.get("Role")
        if role == "home":
            home_team = team.get("TeamId")
        elif role == "guest":
            away_team = team.get("TeamId")

    sections = {}
    for _, el in ET.iterparse(trk_path, events=("end",)):
        if el.tag != "FrameSet":
            continue
        sec = el.get("GameSection")
        team = el.get("TeamId")
        pid = el.get("PersonId")
        s = sections.setdefault(sec, {"ball": None, "players": {}})
        frames = el.findall("Frame")
        n = np.array([int(f.get("N")) for f in frames])
        x = np.array([float(f.get("X")) for f in frames], dtype=np.float32)
        y = np.array([float(f.get("Y")) for f in frames], dtype=np.float32)
        if team in ("BALL", "Ball") or pid == "DFL-OBJ-0000XT":
            poss = np.array([int(f.get("BallPossession") or 0) for f in frames], dtype=np.int8)
            stat = np.array([int(f.get("BallStatus") or 0) for f in frames], dtype=np.int8)
            s["ball"] = (n, x, y, poss, stat)
        elif team in (home_team, away_team):
            s["players"][pid] = (team == home_team, n, x, y)
        el.clear()

    pids_h = sorted({p for s in sections.values() for p, v in s["players"].items() if v[0]})
    pids_a = sorted({p for s in sections.values() for p, v in s["players"].items() if not v[0]})
    idx_h = {p: i for i, p in enumerate(pids_h)}
    idx_a = {p: i for i, p in enumerate(pids_a)}

    halves, chunks_b, chunks_h, chunks_a, chunks_l = [], [], [], [], []
    t0 = 0
    for sec in ("firstHalf", "secondHalf"):
        s = sections[sec]
        n, x, y, poss, stat = s["ball"]
        base = int(n.min())
        T = int(n.max()) - base + 1
        ball = np.full((T, 2), np.nan, np.float32)
        lab = np.full(T, D, np.int8)
        i = n - base
        ball[i, 0], ball[i, 1] = x, y
        alive = stat == 1
        lab[i] = np.where(~alive, D, np.where(poss == 1, H, np.where(poss == 2, A, D)))

        hm = np.full((T, len(pids_h), 2), np.nan, np.float32)
        aw = np.full((T, len(pids_a), 2), np.nan, np.float32)
        for pid, (is_home, pn, px, py) in s["players"].items():
            j = pn - base
            ok = (j >= 0) & (j < T)
            if is_home:
                k = idx_h[pid]
                hm[j[ok], k, 0], hm[j[ok], k, 1] = px[ok], py[ok]
            else:
                k = idx_a[pid]
                aw[j[ok], k, 0], aw[j[ok], k, 1] = px[ok], py[ok]

        chunks_b.append(ball)
        chunks_h.append(hm)
        chunks_a.append(aw)
        chunks_l.append(lab)
        halves.append((t0, t0 + T))
        t0 += T

    return {
        "name": f"idsse_{match_id}",
        "ball": np.concatenate(chunks_b),
        "home": np.concatenate(chunks_h),
        "away": np.concatenate(chunks_a),
        "label": np.concatenate(chunks_l),
        "halves": halves,
    }


def _drift_noise(rng, shape, sd, knot=50):
    """Piecewise-linear slow drift sampled every `knot` frames (2.0s at 25 fps)."""
    T = shape[0]
    n_k = T // knot + 2
    knots = rng.normal(0, sd, (n_k,) + tuple(shape[1:])).astype(np.float32)
    x = np.arange(T) / knot
    i0 = np.floor(x).astype(int)
    w = (x - i0).reshape((T,) + (1,) * (len(shape) - 1)).astype(np.float32)
    return knots[i0] * (1 - w) + knots[i0 + 1] * w


def _degrade_players(home, away, rng, player_keep=10.2 / 11, slot_len_s=20.0):
    out = []
    for P in (home.copy(), away.copy()):
        T_, K, _ = P.shape
        drop = np.zeros((T_, K), bool)
        hz_p = (1 - player_keep) / (player_keep * 50.0)
        for k in range(K):
            for s0 in np.flatnonzero(rng.random(T_) < hz_p):
                drop[s0 : s0 + int(rng.exponential(50)) + 1, k] = True
        P[drop] = np.nan
        P += _drift_noise(rng, P.shape, 0.2)
        blk = int(slot_len_s * FPS)
        for s0 in range(0, T_, blk):
            P[s0 : s0 + blk] = P[s0 : s0 + blk, rng.permutation(K)]
        out.append(P)
    return out[0], out[1]


def degrade_v3(
    m,
    seed=0,
    p_dead_hidden=0.84,
    live_gap_frac=0.07,
    live_gap_median_s=4.0,
    player_keep=10.2 / 11,
    slot_len_s=20.0,
):
    """Apply realistic tracking noise v3 calibrated to SkillCorner/ATD gap statistics."""
    rng = np.random.default_rng(seed + 31)
    ball = m["ball"].copy()
    lab = m["label"]
    T = len(ball)
    miss = np.zeros(T, bool)

    dead = (lab == D).astype(int)
    d = np.diff(np.r_[0, dead, 0])
    for s0, e0 in zip(np.flatnonzero(d == 1), np.flatnonzero(d == -1)):
        if rng.random() < p_dead_hidden:
            a = s0 + int(rng.uniform(0, 1.0) * FPS)
            b = e0 - int(rng.uniform(0, 0.6) * FPS)
            if b > a:
                miss[a:b] = True

    sp = np.zeros(T, np.float32)
    sp[1:] = np.nan_to_num(np.sqrt((np.diff(ball, axis=0) ** 2).sum(-1)) * FPS)
    allp = np.concatenate([m["home"], m["away"]], axis=1)
    with np.errstate(invalid="ignore"):
        crowd = np.nansum(np.sqrt(((allp - ball[:, None]) ** 2).sum(-1)) < 3.0, axis=1)
    live = lab != D
    hz = (1.0 + 2.0 * (sp > 15) + 0.5 * np.minimum(crowd, 4)) * live
    med = live_gap_median_s * FPS
    mean_len = med * np.exp(0.5 * 0.8 ** 2)
    hz *= live_gap_frac * live.sum() / (hz.sum() * mean_len)
    for s0 in np.flatnonzero(rng.random(T) < hz):
        miss[s0 : s0 + int(rng.lognormal(np.log(med), 0.8)) + 1] = True

    ball[miss] = np.nan
    ball += _drift_noise(rng, ball.shape, 0.3)
    home, away = _degrade_players(m["home"], m["away"], rng, player_keep, slot_len_s)

    out = dict(m)
    out.update(ball=ball, home=home, away=away)
    return out


def skillcorner_match_ids(sc_dir):
    matches_path = os.path.join(sc_dir, "matches.json")
    if not os.path.isfile(matches_path):
        raise FileNotFoundError(
            f"Missing SkillCorner matches.json in {sc_dir}. "
            "Clone github.com/SkillCorner/opendata @ 4340d27 into external/skillcorner/."
        )
    with open(matches_path, encoding="utf-8") as f:
        ms = json.load(f)
    return sorted(
        str(m["id"])
        for m in ms
        if os.path.exists(os.path.join(sc_dir, f"{m['id']}_tracking_extrapolated.jsonl"))
    )


def _upsample_10_to_25(x, n_out):
    src_fps = 10.0
    t = np.arange(n_out) * src_fps / FPS
    i0 = np.clip(np.floor(t).astype(int), 0, len(x) - 1)
    i1 = np.clip(i0 + 1, 0, len(x) - 1)
    w = (t - np.floor(t)).reshape((-1,) + (1,) * (x.ndim - 1)).astype(np.float32)
    return (x[i0] * (1 - w) + x[i1] * w).astype(np.float32)


def load_skillcorner_match(mid, sc_dir, slot_len_s=20.0, seed=0, extrapolated_players=True):
    """Load a SkillCorner Open Data match upsampled to 25 fps with 20s slot shuffling."""
    with open(os.path.join(sc_dir, f"{mid}_match.json"), encoding="utf-8") as f:
        meta = json.load(f)
    home_id = meta["home_team"]["id"]
    team_of = {p["id"]: (p["team_id"] == home_id) for p in meta["players"]}
    pids_h = sorted(p for p, h in team_of.items() if h)
    pids_a = sorted(p for p, h in team_of.items() if not h)
    ih = {p: k for k, p in enumerate(pids_h)}
    ia = {p: k for k, p in enumerate(pids_a)}

    with open(os.path.join(sc_dir, f"{mid}_tracking_extrapolated.jsonl"), encoding="utf-8") as f:
        rows = [json.loads(line) for line in f]
    T10 = rows[-1]["frame"] + 1
    ball = np.full((T10, 2), np.nan, np.float32)
    home = np.full((T10, len(pids_h), 2), np.nan, np.float32)
    away = np.full((T10, len(pids_a), 2), np.nan, np.float32)
    grp = np.full(T10, -1, np.int8)

    for r in rows:
        f = r["frame"]
        b = r["ball_data"]
        if b and b.get("is_detected") and b.get("x") is not None:
            ball[f] = (b["x"], b["y"])
        g = (r.get("possession") or {}).get("group")
        grp[f] = 0 if g == "home team" else 1 if g == "away team" else -1
        for p in r["player_data"]:
            if p["player_id"] not in team_of or (not extrapolated_players and not p.get("is_detected")):
                continue
            if team_of[p["player_id"]]:
                home[f, ih[p["player_id"]]] = (p["x"], p["y"])
            else:
                away[f, ia[p["player_id"]]] = (p["x"], p["y"])

    phases = pd.read_csv(os.path.join(sc_dir, f"{mid}_phases_of_play.csv"))
    live = np.zeros(T10, bool)
    phase_team = np.full(T10, -1, np.int8)
    for _, ph in phases.iterrows():
        a, b = int(ph.frame_start), int(ph.frame_end) + 1
        live[a:b] = True
        phase_team[a:b] = 0 if ph.team_in_possession_id == home_id else 1

    lab10 = np.full(T10, D, np.int8)
    d = np.diff(np.r_[0, live.astype(int), 0])
    for a, b in zip(np.flatnonzero(d == 1), np.flatnonzero(d == -1)):
        g = grp[a:b].astype(float)
        g[g < 0] = np.nan
        s_ser = pd.Series(g).ffill().bfill().values
        s_ser = np.where(np.isnan(s_ser), phase_team[a:b], s_ser)
        lab10[a:b] = np.where(s_ser == 0, H, A)

    src_fps = 10.0
    n25 = int(T10 * FPS / src_fps)
    halves = [
        (int(round(p["start_frame"] * FPS / src_fps)), int(round((p["end_frame"] + 1) * FPS / src_fps)))
        for p in meta["match_periods"]
    ]
    halves = [(a, min(b, n25)) for a, b in halves]
    lab25 = lab10[np.clip(np.round(np.arange(n25) * src_fps / FPS).astype(int), 0, T10 - 1)]

    ball25 = _upsample_10_to_25(ball, n25)
    home25 = _upsample_10_to_25(home, n25)
    away25 = _upsample_10_to_25(away, n25)
    rng = np.random.default_rng(seed)
    blk = int(slot_len_s * FPS)
    for P in (home25, away25):
        for s0 in range(0, n25, blk):
            P[s0 : s0 + blk] = P[s0 : s0 + blk, rng.permutation(P.shape[1])]

    return {
        "name": f"scx_{mid}",
        "ball": ball25,
        "home": home25,
        "away": away25,
        "label": lab25,
        "halves": halves,
        "poss_weight": 0.0,  # Live/dead supervision only; possession definitions differ in SkillCorner
        "step": 6,
    }


