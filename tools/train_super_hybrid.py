def fit_trees(train_items):
    """Train (live_clf, home_clf) HistGradientBoosting classifiers on 162 asymmetric features."""
    Xs, yls, yhs, pws = [], [], [], []
    for m, s in train_items:
        step = m.get("step", 3)
        pw_val = m.get("poss_weight", 1.0)
        for a, b in m["halves"]:
            feat_df = extract_tree_features(s, a, b)
            sl = slice(0, b - a, step)
            lab = m["label"][a:b][sl]
            Xs.append(feat_df.iloc[sl])
            yls.append((lab != D).astype(int))
            yhs.append((lab == H).astype(int))
            pws.append(np.full(len(lab), pw_val))

    X_all = pd.concat(Xs, ignore_index=True)
    yl = np.concatenate(yls)
    yh = np.concatenate(yhs)
    pw = np.concatenate(pws)

    live_clf = HistGradientBoostingClassifier(**HGB_PARAMS).fit(X_all, yl)
    alive = (yl == 1) & (pw > 0)
    home_clf = HistGradientBoostingClassifier(**HGB_PARAMS).fit(X_all[alive], yh[alive])
    return live_clf, home_clf


def fit_tcn(train_matches, epochs=12, chunk=512, batch=16, lr=2e-3, seed=0, alpha=0.5, max_steps_per_epoch=52):
    """Train PerObjectTCN (2D-Conv over objects x time, masked set pooling)."""
    torch.manual_seed(seed)
    rng = np.random.default_rng(seed)

    data = []
    for m in train_matches:
        pw = float(m.get("poss_weight", 1.0))
        for a, b in m["halves"]:
            x, vis = tensorize_tcn(m, a, b)
            lab = m["label"][a:b:STRIDE]
            tg = tag_tensor(m, a, b)
            data.append((x, vis, (lab != D).astype(np.float32), (lab == H).astype(np.float32), tg, pw))

    dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    net = PerObjectTCN(hid=48, dils=(1, 2, 4, 8, 16, 32), drop=0.1, n_tag=len(PHYS_KEYS)).to(dev)
    opt = torch.optim.AdamW(net.parameters(), lr=lr, weight_decay=1e-4)

    total = sum(d[0].shape[-1] for d in data)
    steps_per_epoch = max(1, total // (chunk * batch))
    if max_steps_per_epoch:
        steps_per_epoch = min(steps_per_epoch, max_steps_per_epoch)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, lr, total_steps=epochs * steps_per_epoch)
    lens = np.array([d[0].shape[-1] for d in data], float)

    for ep in range(epochs):
        net.train()
        tot = 0.0
        for _ in range(steps_per_epoch):
            xs, vs, yl, yh, tgs, pws = [], [], [], [], [], []
            for _ in range(batch):
                i = rng.choice(len(data), p=lens / lens.sum())
                x, vis, l_arr, h_arr, tg, pw = data[i]
                s0 = int(rng.integers(0, x.shape[-1] - chunk))
                pws.append(np.full(chunk, pw, np.float32))
                tgs.append(tg[:, s0 : s0 + chunk])
                xs.append(x[..., s0 : s0 + chunk])
                vs.append(vis[:, s0 : s0 + chunk])
                yl.append(l_arr[s0 : s0 + chunk])
                yh.append(h_arr[s0 : s0 + chunk])

            xb = torch.from_numpy(np.stack(xs)).to(dev)
            vb = torch.from_numpy(np.stack(vs)).to(dev)
            ylb = torch.from_numpy(np.stack(yl)).to(dev)
            yhb = torch.from_numpy(np.stack(yh)).to(dev)
            tb = torch.from_numpy(np.stack(tgs)).to(dev)

            out = net(xb, vb, tb)
            l_da = F.binary_cross_entropy_with_logits(out[:, 0], ylb)
            pwb = torch.from_numpy(np.stack(pws)).to(dev) * ylb
            l_po = (F.binary_cross_entropy_with_logits(out[:, 1], yhb, reduction="none") * pwb).sum() / pwb.sum().clamp(min=1)
            loss = alpha * l_da + (1.0 - alpha) * l_po

            opt.zero_grad()
            loss.backward()
            opt.step()
            sched.step()
            tot += loss.item()
        print(f"  epoch {ep + 1:02d}/{epochs} loss={tot / steps_per_epoch:.4f}", flush=True)

    return net.cpu()


def _predict_trees(models, m, s):
    live_clf, home_clf = models
    n_frames = len(m["ball"])
    pl = np.full(n_frames, np.nan, np.float32)
    ph = np.full(n_frames, np.nan, np.float32)
    for a, b in m["halves"]:
        feat_df = extract_tree_features(s, a, b)
        pl[a:b] = live_clf.predict_proba(feat_df)[:, 1]
        ph[a:b] = home_clf.predict_proba(feat_df)[:, 1]
    return pl, ph


def _decode_halves(pl, ph, halves, c_team, c_dead, temp=1.0):
    out = np.full(len(pl), pm.X, dtype=np.int8)
    for a, b in halves:
        out[a:b] = viterbi_3state_fast(pl[a:b], ph[a:b], c_team=c_team, c_dead=c_dead, temp=temp)
    return out


def select_hyperparams_lomo(dfl_items, sc_items):
    """Reference reconstruction of 7-fold DFL v3 LOMO selection (not re-run in CPU packaging)."""
    oof = {v: [] for v in ("A", "B")}
    for j, (te_m, te_s) in enumerate(dfl_items):
        others = [item for k, item in enumerate(dfl_items) if k != j]
        for var, extra in (("A", []), ("B", sc_items)):
            tr_items = others + extra
            trees = fit_trees(tr_items)
            net = fit_tcn([m for m, _ in tr_items])
            g_pl, g_ph = _predict_trees(trees, te_m, te_s)
            t_pl, t_ph = predict_tcn_probabilities(net, te_m)
            oof[var].append((t_pl, t_ph, g_pl, g_ph))

    true_labels = []
    for m, _ in dfl_items:
        arr = np.full(len(m["label"]), pm.X, dtype=np.int8)
        for a, b in m["halves"]:
            arr[a:b] = m["label"][a:b]
        true_labels.append(arr)

    # Step 1: Select per-variant blend weights over the 420-point grid on DFL LOMO folds
    w_chosen = {}
    n_folds = len(dfl_items)
    for var in ("A", "B"):
        scores = np.zeros((len(VARIANT_GRID), n_folds))
        for k, (w, ct, cd, tp) in enumerate(VARIANT_GRID):
            for j, (m, _) in enumerate(dfl_items):
                tpl, tph, gpl, gph = oof[var][j]
                pred = _decode_halves(
                    blend_probabilities(tpl, gpl, w), blend_probabilities(tph, gph, w), m["halves"], ct, cd, tp
                )
                scores[k, j] = pm.evaluate(true_labels[j], pred)["spell_f1_mean"]
        fold_ws = [
            VARIANT_GRID[int(np.argmax(np.delete(scores, j, axis=1).mean(axis=1)))][0]
            for j in range(n_folds)
        ]
        best_idx = int(np.argmax(scores.mean(axis=1)))
        w_best = VARIANT_GRID[best_idx][0]
        w_chosen[var] = w_best
        n_agree = sum(1 for fw in fold_ws if fw == w_best)
        print(
            f"  Variant {var} best DFL v3 setting {VARIANT_GRID[best_idx]} "
            f"(mean spellF1 {scores[best_idx].mean():.4f}, fold consensus w={w_best}: {n_agree}/{n_folds} folds)"
        )

    # Step 2: Select decoupled AB Viterbi parameters over 60-point decoder grid on DFL LOMO folds
    w_live, w_poss = w_chosen["B"], w_chosen["A"]
    ab_scores = np.zeros((len(DECODER_GRID), len(dfl_items)))
    for k, (ct, cd, tp) in enumerate(DECODER_GRID):
        for j, (m, _) in enumerate(dfl_items):
            b_tpl, _, b_gpl, _ = oof["B"][j]
            _, a_tph, _, a_gph = oof["A"][j]
            pl = blend_probabilities(b_tpl, b_gpl, w_live)
            ph = blend_probabilities(a_tph, a_gph, w_poss)
            pred = _decode_halves(pl, ph, m["halves"], ct, cd, tp)
            ab_scores[k, j] = pm.evaluate(true_labels[j], pred)["spell_f1_mean"]

    lomo_spells = [
        ab_scores[int(np.argmax(np.delete(ab_scores, j, axis=1).mean(axis=1))), j]
        for j in range(len(dfl_items))
    ]
    best_dec = DECODER_GRID[int(np.argmax(ab_scores.mean(axis=1)))]
    print(
        f"  Decoupled AB LOMO spellF1={np.mean(lomo_spells):.4f} | "
        f"w_live={w_live}, w_poss={w_poss}, costs(c_team, c_dead, temp)={best_dec}"
    )
    return {"w_live": w_live, "w_poss": w_poss, "costs": best_dec, "lomo_spell_f1": float(np.mean(lomo_spells))}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", default="all", choices=["A", "B", "all"])
    ap.add_argument("--model", default="all", choices=["trees", "tcn", "all"])
    ap.add_argument("--idsse-dir", default=os.path.join(ROOT, "external", "idsse"))
    ap.add_argument("--sc-dir", default=os.path.join(ROOT, "external", "skillcorner"))
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "models"))
    ap.add_argument("--overwrite", action="store_true", help="overwrite existing frozen weight files")
    ap.add_argument("--select-hyperparams", action="store_true", help="run 7-fold DFL v3 LOMO grid selection")
    args = ap.parse_args()

    variants = ["A", "B"] if args.variant == "all" else [args.variant]
    models = ["trees", "tcn"] if args.model == "all" else [args.model]
    os.makedirs(args.out_dir, exist_ok=True)

    print("Loading and degrading 7 IDSSE Bundesliga matches (noise v3, seed=0)...", flush=True)
    dfl_items = [_attach_signals(degrade_v3(load_idsse_centered(mid, args.idsse_dir), seed=0)) for mid in IDSSE_IDS]

    sc_items = []
    if "B" in variants or args.select_hyperparams:
        print("Loading 20 SkillCorner A-League matches (extrapolated_players=True, live/dead only)...", flush=True)
        sc_ids = skillcorner_match_ids(args.sc_dir)
        sc_items = [_attach_signals(load_skillcorner_match(mid, args.sc_dir)) for mid in sc_ids]

    if args.select_hyperparams:
        select_hyperparams_lomo(dfl_items, sc_items)
        return

    for var in variants:
        train_items = dfl_items + (sc_items if var == "B" else [])
        tag = f"variant_{var.lower()}"
        if "trees" in models:
            out_pkl = os.path.join(args.out_dir, f"hgb_{tag}.pkl")
            if os.path.exists(out_pkl) and not args.overwrite:
                print(f"[skip] {out_pkl} exists (pass --overwrite to retrain)")
            else:
                print(f"Training {out_pkl} on {len(train_items)} external matches...", flush=True)
                bundle = fit_trees(train_items)
                with open(out_pkl, "wb") as f:
                    pickle.dump(bundle, f)
                print(f"[ok]   wrote {out_pkl}")

        if "tcn" in models:
            out_pt = os.path.join(args.out_dir, f"tcn_{tag}.pt")
            if os.path.exists(out_pt) and not args.overwrite:
                print(f"[skip] {out_pt} exists (pass --overwrite to retrain)")
            else:
                print(f"Training {out_pt} on {len(train_items)} external matches...", flush=True)
                net = fit_tcn([m for m, _ in train_items])
                torch.save(net.state_dict(), out_pt)
                print(f"[ok]   wrote {out_pt}")


if __name__ == "__main__":
    main()
