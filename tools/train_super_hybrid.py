"""External-only training script for the Super-Hybrid models (Variant A and B).

Trains the frozen weights shipped in models/:
- Variant A (models/tcn_variant_a.pt, models/hgb_variant_a.pkl):
    Trained on the 7 public IDSSE Bundesliga matches (Bassek et al., 2025; CC BY 4.0)
    with simulated automatic-tracking noise v3 (no 0.2s ball smoothing). Used for P(home | live).
- Variant B (models/tcn_variant_b.pt, models/hgb_variant_b.pkl):
    Trained on the 7 IDSSE matches (noise v3) + 20 SkillCorner Open Data A-League matches
    (github.com/SkillCorner/opendata @ commit 4340d27; MIT licence) with poss_weight=0.0 on
    SkillCorner so only the live/dead head is trained on broadcast tracking. Used for P(live).

Never reads the provided BAR-ATH match or any BAR-ATH ground truth.

Provenance note: The base 2-model blend/Viterbi hyperparameters (`w_live=0.50`,
`w_poss=0.75`, `c_team=4.0`, `c_dead=25.0`, `temp=1.0`) were obtained from external
IDSSE LOMO sweeps on 7 matches, and `--select-hyperparams` reproduces that LOMO grid search.
Production inference reads `config/ensemble_weights.json` (generated by `tools/sweep_ensemble_weights.py`).

Requirements for retraining from scratch:
- Download IDSSE raw XMLs into external/idsse/ via `python tools/fetch_external.py --only idsse`.
- Place the 20 SkillCorner Open Data matches (matches.json, <id>_match.json,
  <id>_tracking_extrapolated.jsonl, <id>_phases_of_play.csv) into external/skillcorner/.

Usage:
    python tools/train_super_hybrid.py --variant all --model all --overwrite
    python tools/train_super_hybrid.py --select-hyperparams  # LOMO selection of blend & Viterbi costs
"""

